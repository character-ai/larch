"""Frozen Python behavior for the issue #8058 session-env writer cutover.

This reproduces `python/larch/state/session_env.py` as it behaved at cutover for
`session write-env`, `write-design-env`, `write-implement-env`,
`clear-implement-pointer`, `persist-run-flags`, `write-run-params`,
`restore-finalize-state`, and `resolve-trusted-design-env`, with three deliberate
omissions that are not part of any command contract:

* `logging_util.quiet_init` file routing. It duplicates stdout and stderr into a
  per-invocation `$TMPDIR/larch-quiet-*.log` while leaving the contract streams
  pointed at the original descriptors, so a caller sees identical bytes either
  way. The Rust owner writes the same bytes without the observability copy.
* Outbound redaction of breadcrumb diagnostics. The Rust owner keeps redaction;
  this reference omits it because the rules rewrite only `/Users/<user>/<repo>/`
  and `/home/<user>/<repo>/` prefixes, which no sandbox path can match.
* The best-effort `run-log write` delegation at the end of
  `restore-finalize-state`. Both owners spawn it only when the durable state
  carries both a bail reason and a run id, and both discard its result; the
  golden matrix covers the no-bail-reason path, and a `larch-cli` integration
  test covers the delegation itself against a fake plugin root.

Two differences are known and intentional, neither observable to a caller that
branches on exit codes:

* `clap` consumes a lone `--` before the Rust command sees it, so a trailing
  `--` exits 0 in Rust and 1 or 2 here. No production caller passes it. The same
  boundary already applies to the #8056 and #8057 owners.
* A carriage return inside `ship-pr-state.sh` raises an uncaught `ValueError`
  here, because `restore-finalize-state` never guarded its reads; the Rust owner
  reports the same diagnostic on stderr and exits 1 instead of printing a
  traceback. This case stays out of the byte-compared golden matrix.
* `--issue-number` accepts any Unicode digit here, because Python's
  `str.isdigit` does; the Rust owner accepts ASCII digits only. Both write the
  value into a wire file consumed as a GitHub issue number, which is always
  ASCII, so the Rust owner is the stricter of two acceptable readings.
* `--output` naming an existing directory is refused by both, but the wording
  differs: this reference surfaces the operating system's rename errno, and the
  Rust owner surfaces its confinement refusal. Exit code, refusal, and the
  untouched target are identical, so this case stays out of the golden matrix.

The generated design env keeps its `generated by session_env.py` banner: the
acceptance criterion is byte-identical output, so the banner is wire content,
not an attribution.
"""
