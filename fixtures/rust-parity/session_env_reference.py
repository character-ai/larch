def write_env_main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="session write-env", add_help=False)
    parser.add_argument("--output")
    parser.add_argument("--repo", default="")
    parser.add_argument("--repo-root", default="")
    parser.add_argument("--repo-unavailable")
    for flag in ("codex-present", "cursor-present", "codex-available", "cursor-available",
                 "claude-binary-found", "codex-binary-found", "cursor-binary-found", "auto-mode"):
        parser.add_argument(f"--{flag}", default="")
    parser.add_argument("--forked-target", default="false")
    for flag in ("timing-ledger", "token-session-id", "claude-source-file",
                 "prev-implement-tmpdir", "dynamic-archetypes", "run-id", "live-mutation-ok"):
        parser.add_argument(f"--{flag}", default="")
    parser.add_argument("--plugin-root-only", action="store_true")
    parser.add_argument("--value", default="")
    try:
        args = parser.parse_args(argv)
    except SystemExit:
        return 1
    try:
        if not args.output:
            raise ValueError("Missing required arguments: --output, --repo-unavailable")
        out_path = Path(args.output)
        if args.plugin_root_only:
            if validate_plugin_root_value(args.value):
                write_plugin_root_env(out_path, args.value)
            return 0
        if args.repo_unavailable is None:
            raise ValueError("Missing required arguments: --output, --repo-unavailable")
        for flag in ("codex_present", "cursor_present", "codex_available", "cursor_available",
                     "claude_binary_found", "codex_binary_found", "cursor_binary_found",
                     "auto_mode", "live_mutation_ok"):
            value = getattr(args, flag)
            if value:
                parse_bool_arg(value, f"--{flag.replace('_', '-')}")
        parse_bool_arg(args.forked_target, "--forked-target")
        if args.token_session_id and not _SAFE_ID_RE.match(args.token_session_id):
            raise ValueError("Invalid --token-session-id: must match ^[A-Za-z0-9_.-]{1,128}$")
        validate_path_arg_value(args.claude_source_file, "--claude-source-file")
        validate_path_arg_value(args.timing_ledger, "--timing-ledger")
        if args.prev_implement_tmpdir:
            validate_path_arg_value(args.prev_implement_tmpdir, "--prev-implement-tmpdir")
            if not args.prev_implement_tmpdir.startswith("/"):
                raise ValueError("Invalid --prev-implement-tmpdir: must be an absolute path")
        plugin_root = os.environ.get("CLAUDE_PLUGIN_ROOT", "")
        if plugin_root and not validate_plugin_root_value(plugin_root):
            raise ValueError("Invalid CLAUDE_PLUGIN_ROOT: must be an absolute path matching ^[A-Za-z0-9_./~+-]{1,512}$")
        if args.dynamic_archetypes and args.dynamic_archetypes not in {"0", "1"}:
            raise ValueError("Invalid --dynamic-archetypes: must be an integer from 0 to 1")
        if args.run_id and not _SAFE_RUN_ID_RE.match(args.run_id):
            raise ValueError("Invalid --run-id: must match ^[A-Za-z0-9._-]{1,128}$")
        repo_root = args.repo_root.strip() or fallback_repo_root()
        validate_repo_root_value(repo_root, "--repo-root")
        rows: list[tuple[str, str]] = [
            ("REPO", args.repo),
            ("REPO_UNAVAILABLE", args.repo_unavailable),
            ("FORKED_TARGET", args.forked_target),
            ("LARCH_EXTERNAL_HEALTH_CHECK_TIMEOUT", external_timeout()),
        ]
        for key, value in (
            ("CLAUDE_BINARY_FOUND", args.claude_binary_found),
            ("CODEX_BINARY_FOUND", args.codex_binary_found),
            ("CURSOR_BINARY_FOUND", args.cursor_binary_found),
            ("LARCH_AUTO_MODE", args.auto_mode),
            ("LARCH_TIMING_LEDGER", args.timing_ledger),
            ("LARCH_TOKEN_SESSION_ID", args.token_session_id),
            ("LARCH_CLAUDE_SOURCE_FILE", args.claude_source_file),
            ("PREV_IMPLEMENT_TMPDIR", args.prev_implement_tmpdir),
            ("LARCH_DYNAMIC_ARCHETYPES_MAX", args.dynamic_archetypes),
            ("LARCH_RUN_ID", args.run_id),
            ("LARCH_LIVE_MUTATION_OK", args.live_mutation_ok),
            ("REPO_ROOT", repo_root),
            ("LARCH_CLAUDE_PLUGIN_ROOT", plugin_root),
        ):
            if value:
                rows.append((key, value))
        validate_writer_keys(rows, WRITE_ENV_KEYS)
        validate_no_newlines(rows)
        if args.output == "/dev/null":
            return 0
        confirm_writable(out_path, args.output)
        atomic_write(out_path, kv_text(rows))
        if plugin_root:
            write_plugin_root_env(out_path.parent / "plugin-root.env", plugin_root)
        return 0
    except (OSError, ValueError) as error:
        print(f"ERROR={error}", file=sys.stderr)
        return 1


