def cache_sessions_root() -> Path:
    xdg = os.environ.get("XDG_CACHE_HOME")
    if xdg:
        base = xdg
    else:
        home = os.environ.get("HOME", "")
        base = f"{home}/.cache" if home else f"{TMP_FALLBACK}/.cache"
    return Path(base) / "larch" / "sessions"


def allowed_roots() -> tuple[Path, ...]:
    return (Path(TMP_FALLBACK), Path("/private/tmp"), Path("/var/folders"),
            Path("/private/var/folders"), cache_sessions_root())


def _resolved(path: Path) -> Path:
    return path.resolve(strict=False)


def _under(path: Path, root: Path) -> bool:
    try:
        resolved, resolved_root = _resolved(path), _resolved(root)
    except OSError:
        return False
    return resolved == resolved_root or resolved_root in resolved.parents


def _strictly_under(path: Path, root: Path) -> bool:
    try:
        resolved, resolved_root = _resolved(path), _resolved(root)
    except OSError:
        return False
    return resolved_root in resolved.parents


def is_allowed_session_tmpdir(path: Path) -> bool:
    return any(_strictly_under(path, root) for root in allowed_roots())


def writer_target_allowed(path: Path) -> bool:
    return any(_under(path, root) for root in allowed_roots())


def safe_output_parent(path: Path) -> bool:
    parent = path.parent
    return parent.exists() and parent.is_dir() and not parent.is_symlink()


def assert_no_symlink_path_or_ancestors(path: Path) -> None:
    current = path if path.is_absolute() else Path.cwd() / path
    while True:
        if current.is_symlink():
            raise OSError(f"refusing symlinked path or ancestor: {current}")
        if current == current.parent:
            return
        current = current.parent


def atomic_write(path: Path, text: str, *, create_parent: bool = False, mode: int = 0o600) -> None:
    assert_no_symlink_path_or_ancestors(path if path.is_absolute() else Path.cwd() / path)
    if create_parent:
        path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        raise OSError(f"refusing to write through symlink: {path}")
    temp = path.with_suffix(path.suffix + ".tmp")
    with suppress(FileNotFoundError):
        temp.unlink()
    descriptor = os.open(str(temp), os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, mode)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
    except BaseException:
        with suppress(OSError):
            temp.unlink()
        raise
    os.chmod(temp, mode)
    temp.replace(path)


def kv_text(rows: list[tuple[str, str]]) -> str:
    return "".join(f"{key}={value}\n" for key, value in rows)


def read_kv_file_text(path: Path) -> str:
    text = path.read_bytes().decode("utf-8", errors="replace")
    if "\r" in text:
        raise ValueError(f"session env file contains carriage return: {path}")
    return text


def read_kv_raw(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    values: dict[str, str] = {}
    for raw in read_kv_file_text(path).splitlines():
        if not raw or raw.startswith("#") or "=" not in raw:
            continue
        key, value = raw.split("=", 1)
        values[key] = value
    return values


def parse_allowlisted_env_line(raw: str, allowlist: frozenset[str], *, reject_newline_rhs: bool) -> tuple[str, str] | None:
    line = raw.strip()
    if not line or line.startswith("#"):
        return None
    line = line.removeprefix("export ")
    if "=" not in line:
        return None
    key, rhs = line.split("=", 1)
    key = key.strip()
    if key not in allowlist or not _KEY_RE.match(key):
        return None
    if reject_newline_rhs and ("\n" in rhs or "\r" in rhs):
        return None
    try:
        parts = shlex.split(rhs, posix=True)
    except ValueError:
        return None
    if len(parts) > 1:
        return None
    value = parts[0] if parts else ""
    return None if "\n" in value or "\r" in value else (key, value)


def validate_no_newlines(rows: list[tuple[str, str]]) -> None:
    for key, value in rows:
        if "\n" in value or "\r" in value:
            raise ValueError(f"value for {key} contains newline or carriage return")


def validate_writer_keys(rows: list[tuple[str, str]], allowed: frozenset[str]) -> None:
    for key, _ in rows:
        if key not in allowed:
            raise ValueError(f"disallowed writer key: {key}")


def external_timeout() -> str:
    value = os.environ.get("LARCH_EXTERNAL_HEALTH_CHECK_TIMEOUT", "60")
    return value if value.isdigit() else "60"


def parse_bool_arg(value: str, flag: str) -> None:
    if value not in _BOOL:
        raise ValueError(f"Invalid {flag}: must be true or false")


def validate_plugin_root_value(value: str) -> bool:
    return bool(value) and len(value) <= MAX_PATH_VALUE_LEN and value.startswith("/") and bool(_SAFE_PATH_RE.match(value))


def validate_path_arg_value(value: str, flag: str) -> None:
    if value and (len(value) > MAX_PATH_VALUE_LEN or not _SAFE_PATH_RE.match(value)):
        raise ValueError(f"Invalid {flag}: must match ^[A-Za-z0-9_./~+-]{{1,512}}$")


def validate_repo_root_value(value: str, flag: str) -> None:
    if not value:
        return
    if len(value) > MAX_PATH_VALUE_LEN or "\n" in value or "\r" in value or "\x00" in value:
        raise ValueError(f"Invalid {flag}: must be an absolute single-line path")
    if not value.startswith("/"):
        raise ValueError(f"Invalid {flag}: must be an absolute path")


def valid_repo_value(value: str) -> bool:
    if not value:
        return True
    if value.startswith(("--", "/")) or "../" in value or "\\" in value:
        return False
    if "\n" in value or "\r" in value:
        return False
    return bool(_REPO_RE.match(value))


def fallback_repo_root() -> str:
    return os.environ.get("CLAUDE_PROJECT_DIR", "").strip() or os.environ.get("REPO_ROOT", "").strip()


def sessions_dir() -> Path:
    return Path.home() / ".cache" / "larch" / "sessions"


def design_pointer_path(pid: str) -> Path:
    return sessions_dir() / (f"current-design-env-{pid}.sh" if pid else "current-design-env.sh")


def implement_pointer_path(pid: str) -> Path:
    return sessions_dir() / f"current-implement-env-{pid}.sh"


def write_plugin_root_env(output: Path, value: str) -> None:
    if not value or not validate_plugin_root_value(value):
        return
    if not output.parent.is_dir():
        raise OSError(f"plugin-root.env parent is not a directory: {output.parent}")
    atomic_write(output, f"CLAUDE_PLUGIN_ROOT={value}\nexport CLAUDE_PLUGIN_ROOT\n")


def confirm_writable(target: Path, reported: str) -> None:
    if not writer_target_allowed(target):
        raise ValueError(f"output path not under allowed session root: {reported}")
    if not safe_output_parent(target):
        raise OSError(f"output parent is not a writable directory: {target.parent}")


