def restore_finalize_state_main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="session restore-finalize-state", add_help=False)
    parser.add_argument("--implement-tmpdir", default="")
    try:
        args = parser.parse_args(argv)
        if not args.implement_tmpdir:
            raise ValueError("--implement-tmpdir is required")
        tmpdir = Path(args.implement_tmpdir)
        if not tmpdir.is_dir():
            raise ValueError("--implement-tmpdir must exist")
        if not writer_target_allowed(tmpdir):
            raise ValueError(f"--implement-tmpdir not under allowed session root: {tmpdir}")
    except (SystemExit, ValueError) as error:
        print(f"restore-finalize-state.sh: {error}", file=sys.stderr)
        return 2
    state_file = tmpdir / "ship-pr-state.sh"
    finalize_file = tmpdir / "finalize-state.sh"
    bail_reason_file = tmpdir / "final-bail-reason.txt"
    if not state_file.is_file():
        print(f"restore-finalize-state.sh: warning: missing ship-pr state file: {state_file}", file=sys.stderr)
        return 1
    state = read_kv_raw(state_file)
    existing = read_kv_raw(finalize_file)
    rows: list[tuple[str, str]] = []
    keep_stall = existing.get("STALL_TRACKING", "") == "true"
    existing_stall_step = existing.get("STALL_STEP", "")
    for key in RESTORE_FINALIZE_KEYS:
        value = state.get(key, "")
        if keep_stall:
            if key == "STALL_TRACKING":
                value = "true"
            elif key == "STALL_STEP" and existing_stall_step:
                value = existing_stall_step
        if value == "":
            value = existing.get(key, RESTORE_FINALIZE_DEFAULTS.get(key, ""))
        rows.append((key, value))
    validate_no_newlines(rows)
    atomic_write(finalize_file, kv_text(rows))
    bail_reason = state.get("BAIL_REASON", "")
    atomic_write(bail_reason_file, bail_reason, create_parent=True)
    run_id = state.get("RUN_ID", "")
    if bail_reason and run_id:
        # The legacy verb derived the dispatcher from its own module location;
        # this reference sits one level below the same plugin root.
        root = Path(__file__).resolve().parents[1]
        subprocess.run(  # noqa: S603
            ["python3", str(root / "python" / "cli.py"), "run-log", "write",  # noqa: S607
             "--log-root", str(tmpdir / "larch-logs"), "--skill", "implement",
             "--run-id", run_id, "--batch", "final-bail-reason",
             "--input-file", str(bail_reason_file)],
            check=False, capture_output=True,
        )
    return 0


def resolve_trusted_design_env_main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="session resolve-trusted-design-env", add_help=False)
    parser.add_argument("--session-env-path", required=True)
    parser.add_argument("--claude-pid", default="")
    try:
        args = parser.parse_args(argv)
    except SystemExit:
        return 2
    if args.claude_pid and not _PID_RE.match(args.claude_pid):
        print("Invalid --claude-pid: must be a positive integer of at most 7 decimal digits", file=sys.stderr)
        return 2
    path = Path(args.session_env_path)
    if not args.claude_pid or not path.is_symlink():
        return 1
    if path != design_pointer_path(args.claude_pid):
        return 1
    ancestor = path.parent
    while True:
        if ancestor.is_symlink():
            return 1
        if ancestor == ancestor.parent:
            break
        ancestor = ancestor.parent
    resolved = path.resolve()
    if not resolved.is_file():
        return 1
    print(f"TRUSTED_SOURCE={resolved}")
    return 0


